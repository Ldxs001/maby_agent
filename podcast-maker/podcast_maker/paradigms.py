def get(kind):
    """取范式卡。未知 key 落到 `auto`，不报错也不装懂。"""
    return PARADIGMS.get((kind or "").strip()) or PARADIGMS["auto"]


def chosen_of(item, cfg=None):
    """人指定的是哪张卡：**项目设定 > 全局默认**。没人指定返回**空串**。

    空串与 `"auto"` 不是一回事：空串是「没表态」，探查推断那一层才有资格接手；
    `"auto"` 是明确选了「自适应」这张卡。混成一个值，就等于把「没表态」当成
    「表态了，选自适应」，推断那一层再也进不来。

    顺序只有这一处。探查判附属页、排图分组、写脚本三处都从这里取同一条——
    各判一遍迟早分叉：卡上写着「致谢不播」，探查按通用兜底把它放行、排图又
    按卡去排，就排出一期该念的致谢。分叉也不报错，只是结果自相矛盾。

    **推断不在这里**：探查推断出的类型是"建议"，只在人没指定时兜底。把它并
    进来，等于让建议盖掉人的一次选择。
    """
    forced = str((item or {}).get("paradigm") or "").strip()
    if forced:
        return forced
    g = str((cfg or {}).get("script.paradigm") or "").strip()
    return g if g and g != "auto" else ""


def emotion_level_of(card):
    """情绪档位。卡上没写、或写了个不认识的值，都按 `none`。

    取值只有这一处：写脚本与合成两头都从这里拿，不许各取一次——两边取法一旦
    岔开，就会出现"稿子按略写、合成按不贴说"，或者反过来。**认不出就往"不贴"
    上落**：贴错语气会把整期带偏，不贴只是少了点收窄，不会把稿子弄坏。
    """
    v = str((card or {}).get("emotion_level") or "").strip()
    return v if v in EMOTION_LEVELS else DEFAULT_EMOTION_LEVEL


