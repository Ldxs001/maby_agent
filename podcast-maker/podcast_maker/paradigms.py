# 对话形式：两位主持人的话**怎么交错**
#
# 与 `cast` 不是一回事，也不该挤在同一个字段里：
#   - `cast`（站位）回答「谁懂谁不懂、谁代表听众」——内容上的分工，随素材类型
#     而变（小说里讲故事的那位与方法论里做拆解的那位，站位不同）；
#   - 形式回答「话怎么接」，并给出**两人的连句上限**（`run`）。六种，见下表。
#     **同一套站位可以配任何一种形式**：专家既可以被人一问一答地掏出来，
#     也可以跟人对着辩。
#
# 从前形式是**写死在卡里的**：卡上的 cast 顺手把「A 问 B 答」一起定了，于是
# 不论什么素材、什么风格，出来都是同一套问答节奏；连句上限也因此只能挂在卡上，
# 一个数管两个人。形式单拎成一维之后，上限跟着它走：**卡只给默认形式**
# （`form`），人在配置里选了就顶掉（取值见 `resolve_form()`），选了之后卡上那段
# 站位说明不再出现——是覆盖，不是并列两个来源。
#
# `run` 是**上限不是目标**：不要求两人轮流说到这个数，只要求谁都不许超过它。
# 超限由门禁把整段点出来、交模型并句（v0.34.0 起）——并句减的是行数，不是换人；
# 从前那版是后处理直接翻转说话人，掰出来的就是两个人在念同一段话（A 问的话进了
# B 的嘴）。所以每种形式都留了余量；但**谁也不许
# 没有上限**：哪怕主讲＋捧哏那种，B 连着说 10 句也够了，再多就是模型摁着一个人说、
# 把节目写成了单口。
#
# ## 描述式，不是固定序列
#
# 一种形式由三样说清，各管一件事，写进提示词的位置也不同：
#   - `roles`：A 是谁、B 是谁（各自的句子干哪种活）——「明确 A / B 角」，
#     进【两位主持人】那一节；
#   - `rhythm`：两人怎么接、顺序固定不固定——进【文体依据】那一节（写脚本那
#     一档），因为它是**写作规矩**不是人物介绍；
#   - `run`：两人的连句上限——同样进【文体依据】，并且是门禁判超限的唯一判据。
#
# **六种形式里只有「一问一答」把顺序写死**（A B A B …）——「你问一句我答一句」
# 就是它本身，顺序是它的定义。其余五种一律只描述，不写死顺序：捧哏不等于
# 「主讲每说完一段，捧哏就问一句」，闲聊不等于某一种 A/B 排列，对辩也不是固定
# 的 A A A B B B。写成固定序列就是把一种节奏焊死在所有稿子上：真实对话里谁多说
# 一句、这次谁先开口，本来就该由内容定。
#
# 但**只描述不示范**同样不够用：说了「B 成段推进（三到六句）」，模型照样一句
# 一换——它得先看见一段。所以每种形式都带一条 `example`（进提示词，由
# `example_block()` 渲染）：三到七句实例，只示范**谁在说、连着说几句**，
# 文字内容与本期素材无关、并明写不许照抄。
# 示例与本形式的上限（`run`）**必须一致**——示例自己超限，等于当着模型的面
# 破了规矩（测试钉着这一条）。
# 它和「固定序列」是两件事：示例是一个可能的形状，不是必须照排的顺序。
#
# 另外，**不要把 A 固定成提问者**。`qa` 里 A 确实是提问方，但那是这一种形式的
# 角色约定，不是全体的通则——交替讲述里两人都是讲述人、闲聊里谁接话都行、
# 捧哏的句子也可以只是附和。从前所有形式的 A 都写成「提问、追问」，于是不管选
# 了哪种形式，模型写出来都是 A 问 B 答：形式名换了，稿子没换。
