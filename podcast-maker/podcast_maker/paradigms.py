def resolve_form(card, chosen=""):
    """本期用哪种对话形式。三级顺序，取值只有这一处：

    1. 人在配置里选的（`script.dialogue_form`，非空且认得出来）；
    2. 卡上的默认形式（`card["form"]`）；
    3. `DEFAULT_FORM`。

    **不让「没选」落成空值**：上限总得有一个数，而门禁判超限靠它。写成空值
    再让各处各兜一次底，就会出现提示词按一种形式写、门禁按另一种判的事——
    `max_run` 从前分散在卡上就是这个毛病。
    """
    key = str(chosen or "").strip()
    if key in DIALOGUE_FORMS:
        return key
    key = str((card or {}).get("form") or "").strip()
    if key in DIALOGUE_FORMS:
        return key
    return DEFAULT_FORM


def run_caps(form_key):
    """某种形式下 A / B 各自连着说的上限，返回 `(A, B)`。

    取值只有这一处：写脚本的提示词、它的门禁（超限点整段交模型并句）全从这里拿（同
    `resolve_form` 的理由）。表里缺数按 1 算——**这不是宽松兜底，是让缺数
    立刻显形**：一条形式若连上限都没写，宁可它当场露出来，也不要悄悄按一个
    宽松的数放过去。测试钉着六种形式各自的上限都在。
    """
    f = DIALOGUE_FORMS.get(str(form_key or "").strip()) or {}
    caps = f.get("run") or {}
    out = []
    for who in ("A", "B"):
        try:
            n = int(caps.get(who) or 0)
        except (TypeError, ValueError):
            n = 0
        out.append(max(1, n))
    return tuple(out)


def form_block(form_key):
    """选定的对话形式里「A 是谁、B 是谁」那一段（进【两位主持人】那一节）。

    没选（空值/未知键）返回空串——空串是**默认态**不是错误态：不选就按素材类型
    卡上写的站位走（由 script_engine 的 `_hosts_text()` 负责）。这一条由
    `form_block("") == ""` 钉住。

    **只出角色，不出节奏**：节奏（`rhythm`）与上限（`run`）是写作规矩，归
    `run_block()` 那一节。从前这两样都由一条 `desc` 兼着，整段还挂在「这两位是谁」
    这一节里——模型把它当人物介绍读，不读成写作要求，于是选了「主讲＋捧哏」，
    稿子里 B 照样没成段。人物介绍与写作规矩混在一处，规矩就不算规矩。
    """
    f = DIALOGUE_FORMS.get(str(form_key or "").strip())
    if not f:
        return ""
    roles = f.get("roles") or {}
    lines = ["**本期对话形式：%s**" % f["label"]]
    for who in ("A", "B"):
        if roles.get(who):
            lines.append("- %s 是%s" % (who, roles[who]))
    lines.append("形式与素材类型卡上的站位说明冲突时，**以形式为准**——"
                 "卡上给的是默认形式，这里是人在配置里选定的。")
    return "\n".join(lines)


def rhythm_text(form_key):
    """某种形式的「两人怎么接」那句话。

    **只有一问一答给死顺序**（A B A B …），其余五种是描述——真实对话里谁多说了
    一句、这次谁先开口，本来就该由内容定，写成固定序列等于把一种节奏焊死在所有
    稿子上。整篇、分段、插入三处引同一份（各写一份就会出现写作按一种节奏写、
    补写按另一种补）。
    """
    f = DIALOGUE_FORMS.get(str(form_key or "").strip()) or {}
    return str(f.get("rhythm") or "").strip()


def example_block(form_key, indent=""):
    """某种形式的**形状示范**（三到七句实例），进提示词。

    为什么要有：把节奏说准了也不够——「B 成段推进（三到六句）」「上限 10 句」
    这两句都写了，模型照样一句一换。它得先**看见一段**才知道那是什么样子。
    描述回答「应当怎样」，示范回答「长什么样」，两样都要。

    **只给形状，不给内容**：示范的文字与本期素材无关，并在标题里明写不许照抄
    ——不写这一句，模型会把示范当成「可以这么说」的候选句。

    整篇（`run_block`）、分段（生成要求）、插入（铁律）三处引同一份：各写一份就
    会出现写作按一种节奏写、补写按另一种补（同 `rhythm_text` 的理由）。

    没选形式（空值/未知键）或该形式没写示范时返回空串——空串是默认态，不是错误
    态：调用点按「有就带上」处理。
    """
    f = DIALOGUE_FORMS.get(str(form_key or "").strip()) or {}
    rows = f.get("example") or []
    if not rows:
        return ""
    out = ["**长什么样**（形状示范：文字内容与本期素材无关，只示范谁在说、"
           "连着说几句——**不许照抄这里的字**）"]
    for r in rows:
        out.append('    {"speaker": "%s", "emotion": "%s", "text": "%s"}'
                   % (r.get("speaker", ""), r.get("emotion", ""),
                      r.get("text", "")))
    if indent:
        out = [indent + x for x in out]
    return "\n".join(out)


def register(key, card):
    """注册一张自定义范式。

    范式是数据，扩一张卡不该动排图逻辑。注册进来的卡与内置的同等对待。

    没写 `condense` 的卡在这里补上通用口径——**补在卡上，不做事后兜底**：
    凝缩的依据要能从卡上读出来，运行时才发现缺了再猜，等于把这道工序的标准
    藏进代码里，换一张卡就查不出地图为什么漂了。

    `cast` 留空**不补**：它没有能通用的口径（把「克制」安到一本小说上就是错的）。
    留空时写脚本那一步退回内置的两句分工，卡上写了的以卡为准。
    `form` 没写按 `DEFAULT_FORM` 算（见 `resolve_form()`）——上限是判据，总得
    有一个数；卡上写了个认不出的形式键也落同一处。
    `emotion_level` 没写按 `DEFAULT_EMOTION_LEVEL`（不贴语气指令）算——自定义卡
    不知道自己的文本起伏有多大，默认落在不贴这一侧，贴错了会把整期语气带偏，
    不贴只是少点收窄。
    """
    d = {"label": "", "unit": "", "split": "", "merge": "", "focus": "",
         "condense": DEFAULT_CONDENSE, "flow": "",
         "cast": "", "form": DEFAULT_FORM,
         "emotion_level": DEFAULT_EMOTION_LEVEL,
         "probe": {}, "suggest_minutes": 25, "verified": False}
    d.update(copy.deepcopy(card or {}))
    # 旧卡上可能还带着 `max_run`（v0.31.0 之前上限长在卡上）：上限已归对话形式，
    # 留着这个键只会让人以为改它能改到上限——一个量没有消费者，就不该留在卡上。
    d.pop("max_run", None)
    if not d.get("condense"):
        d["condense"] = DEFAULT_CONDENSE
    pr = d.setdefault("probe", {})
    # 旧的单栏 `misc` 丢弃：它从没被任何一步读过，留着只会让人以为它还在起作用。
    pr.pop("misc", None)
    drop = [str(x).strip() for x in (pr.get("misc_drop") or []) if str(x).strip()]
    keep = [str(x).strip() for x in (pr.get("misc_keep") or []) if str(x).strip()]
    both = [x for x in drop if x in keep]
    if both:
        raise ValueError(
            "范式卡 %s 的附属页清单自相矛盾：%s 同时写在「不播」与「要播」两栏里，"
            "判不出方向。去掉其中一处。" % (key, "、".join(both)))
    pr["misc_drop"], pr["misc_keep"] = drop, keep
    d["custom"] = True
    PARADIGMS[key] = d
    return d


def prompt_block(kind, override=None, stage="plan", extra_focus="",
                 chosen_form=""):
    """把范式拼成提示词里的一段。排图、写脚本共用这一处。

    两档，由 `stage` 选：

    - `stage="plan"`（默认）：**只拼「怎么排」的四项**（切分、整合、重点判据、
      推进方式）加探查的层级与编号期望。排图用这一档。
    - `stage="script"`：只拼「怎么说」的那一项——同一人连着说的上限（取自
      `resolve_form()` 定下的形式，见 `run_block()`）。写脚本用这一档。

    分档不是拆功能，是**同一张卡的两个面**：排图问「怎么切、怎么并」，写脚本问
    「怎么说」。混在一处必然打架——模型会拿「可以连说三句」去凑分期，或者拿
    「一条链不许拆开」去写台词。凝缩规则（`condense`）同理不进任何一档，它是
    给凝缩那一步的，且判据方向与排图相反（凝缩要「不丢」，排图要「选」）。

    站位（`cast`）不在这一档里：它由写脚本那一步的 `_hosts_text()` 拼（选了对话
    形式时被形式的说明顶掉），这里只出上限——两处都拼一份站位，提示词里就会
    出现两段说法，而且是**卡上那份永远顶不掉**（选中形式也照样在）。

    `override` 允许逐字段改写（界面上的高级模式）。人在某一项上有自己的
    判断时，只改那一项，不必为了改一句话换掉整张卡。**要改凝缩规则的措辞
    得走凝缩那一步**（`probe.condense_units` 收的 `card`），不在这里。

    `extra_focus` 是人给这档节目写的一段侧重（项目级，见
    `project_store` 的 `focus_note`）：它与卡上的重点判据**同时生效**，
    不是替换。只进 plan 档——它决定的是分组粒度（侧重的内容可以分得更细、
    次要的合得更粗），属「怎么切、怎么并」，与写脚本那一步无关。

    **空串是「人没写过」，不是「人说了空话」**：那时这个函数的输出与没有
    这个参数时**逐字一致**——老项目的排图不许因为多了一个参数就悄悄换口径。
    """
    card = copy.deepcopy(get(kind))
    for k, v in (override or {}).items():
        if k in card and v:
            card[k] = v
    if stage == "script":
        return run_block(card, chosen_form)
    focus_note = str(extra_focus or "").strip()
    probe = card.get("probe") or {}
    lines = ["【文体依据】（这批素材该怎么组织——%s）" % card["label"],
             "切分单位：**%s**" % card["unit"], ""]
    for key, title in (("split", "切分依据"), ("merge", "整合依据"),
                       ("focus", "重点判据"), ("flow", "推进方式")):
        if card.get(key):
            lines.append("**%s**：%s" % (title, card[key]))
        if key == "focus" and focus_note:
            # 人的侧重与卡上的判据**并列给出**，并明写两者同时生效：写成
            # 「替换」会让模型以为卡上的判据作废，而人往往只想补一句方向。
            lines.append("**本档侧重**（人给这档节目定的方向，与上面的重点判据"
                         "**同时生效**）：%s" % focus_note)
            # 这一句不能省：卡上的重点判据只管「抓什么、什么不播」，
            # 一句话里没有「合并的松紧」。不点明，模型会把人写的方向当成
            # 一条泛泛的内容取向，分组粒度一动也不动。
            lines.append("侧重所指的内容可以分得更细（少合几节、多给期数）；"
                         "次要内容可以合得更粗（多合几节、少占期数）。"
                         "**都在每期的上下限之内**——下限优先，分得再细也不许"
                         "分出料不够的期。")
    if probe.get("unit_hint"):
        lines.append("**层级期望**：%s" % probe["unit_hint"])
    if probe.get("numbering"):
        lines.append("**编号体系**：%s" % probe["numbering"])
    lines.append("")
    lines.append("以上是这批素材的组织依据。期数由你按这些依据做**合并与切分**"
                 "的结果决定——分出几组就是几期，不是先定期数再往里塞。")
    return "\n".join(lines)


def run_block(card, chosen_form=""):
    """写脚本那一档：**两人怎么接** + **各能连着说几句**。

    上限取 `resolve_form()` 定下的那种形式（配置 > 卡上的 `form` > 兜底），与
    门禁同一处取值。**一定要写出来**：门禁按它判，提示词里不说，模型只能自己
    猜一个数——猜大了门禁要把这一段点出来、交回模型并句，猜小了稿子僵成
    一问一答。

    `chosen_form` 是人在配置里选的那一个：它同时决定上限，也决定卡上那段站位
    说明要不要出现（后者归写脚本那一步的 `_hosts_text()`）。站位**不在这里重复
    一遍**——两处都拼一份，提示词里就有两套分工说法，而且是卡上那份永远顶不掉。

    上限之外还多两句：**怎么接**（`rhythm_text`）与**长什么样**（`example_block`）。只给上限就是只划红线，划不出
    形状——「不许超过十句」这句话里推不出「应当连着说几句」，模型拿自己的默认
    节奏（一问一答）来填，完全合规。上限是判据，节奏是写法，两样都要说。

    （卡上的「情绪基调」一行不再出现：语篇标签的口径归词表层（DISCOURSE_HELP），
    写出来只会和词表两套说法打架。）
    """
    form_key = resolve_form(card, chosen_form)
    f = DIALOGUE_FORMS.get(form_key) or {}
    cap_a, cap_b = run_caps(form_key)
    lines = ["【文体依据】（这批素材该怎么写成对话——%s）"
             % str(card.get("label") or "这类素材"), ""]
    rhythm = rhythm_text(form_key)
    if rhythm:
        lines += ["**两人怎么接**（本期对话形式：%s）：%s"
                  % (str(f.get("label") or form_key), rhythm), ""]
    lines += ["**同一人连着说的上限**：A 最多连着说 %d 句、B 最多连着说 %d 句。"
              "这是上限不是目标——各按内容说，谁都不许超过它。" % (cap_a, cap_b),
              ""]
    # 上限与节奏都说了还不够：模型得看见一段，才知道「成段推进」是什么形状。
    # 没有示范的形式（或没选形式）就跳过，不占位置。
    ex = example_block(form_key)
    if ex:
        lines += [ex, ""]
    lines += ["以上是这批素材的对话依据。"]
    return "\n".join(lines)

